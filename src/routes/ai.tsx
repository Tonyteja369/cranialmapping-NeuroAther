import { createFileRoute } from "@tanstack/react-router";
import { Page, Panel, SourceTag, NO_MEDICAL } from "@/components/nsx/ui";
import { useAnalysis } from "@/lib/nsx/analysis";
import { unitLabel } from "@/lib/nsx/dsp";
import { head } from "@/lib/nsx/head";
import { observations } from "@/lib/nsx/observations";

export const Route = createFileRoute("/ai")({
  head: head("AI Analysis", "Deterministic, evidence-backed experimental research observations from measured data."),
  component: AI,
});

function AI() {
  const { sensors, source, usingPreview, state } = useAnalysis("res");
  const { obs, blocked } = observations(sensors, state.settings, state.experiment, unitLabel(state.settings.displayUnit));
  return (
    <Page title="AI-Assisted Analysis" subtitle="Experimental research observations generated by deterministic rules from the computed metrics. No machine-learning model is used until a validated model and dataset exist." actions={<SourceTag source={source} preview={usingPreview} />}>
      <div className="notice">{NO_MEDICAL} These observations do not detect abnormalities or disease.</div>
      {source === "demo" && <div className="notice">Observations below are derived from DEMO DATA and describe synthetic signals.</div>}
      <Panel title={`Experimental research observations (${obs.length})`}>
        <div className="flex flex-col gap-2">
          {obs.map((o, i) => (
            <div key={i} className="rounded-lg border p-3">
              <div className="text-[10px] font-semibold uppercase tracking-wider text-analysis">{o.category} · experimental observation</div>
              <div className="mt-1 text-sm">{o.text}</div>
              <div className="mt-1 font-mono text-[11px] text-muted-foreground">Evidence: {o.evidence}</div>
            </div>
          ))}
          {!obs.length && <div className="text-sm text-muted-foreground">No observations — see below.</div>}
        </div>
      </Panel>
      <Panel title="Analyses not completed">
        <ul className="list-disc pl-5 text-xs">{blocked.map((b) => <li key={b}>{b}</li>)}</ul>
      </Panel>
    </Page>
  );
}
